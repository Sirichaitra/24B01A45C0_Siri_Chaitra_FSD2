"use strict";
//Arrow functions
const addition = (a, b) => {
    return a + b;
};
console.log(addition(10, 20));
//for arrays
const nums = [10, 20, 30, 40];
nums.forEach((num) => {
    console.log(num);
});
//multiple parameters
const multiply = (x, y) => {
    return x * y;
};
console.log(multiply(6, 4));
